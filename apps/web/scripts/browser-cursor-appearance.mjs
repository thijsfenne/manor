import { readFile, writeFile } from 'node:fs/promises'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import { HugeiconsIcon } from '@hugeicons/react'
import { Cursor02Icon } from '@hugeicons/core-free-icons'

// The isolated browser world cannot import React or inherit Manor's stylesheet.
// Export the existing icon and tokens at build time, without a second palette.
const css = await readFile(new URL('../src/styles.css', import.meta.url), 'utf8')
const token = (name) => {
  const value = css.match(new RegExp(`--${name}:\\s*([^;]+);`))?.[1]
  if (!value) throw new Error(`Missing browser cursor token: ${name}`)
  return value.trim()
}
const appearance = {
  color: token('color-busy'),
  outline: token('color-on-media'),
  icon: renderToStaticMarkup(createElement(HugeiconsIcon, {
    icon: Cursor02Icon, size: 24, strokeWidth: 1.5,
    color: token('color-on-media'), fill: token('color-busy'),
  })),
}
await writeFile(new URL('../../desktop/src/browserCursorAppearance.ts', import.meta.url),
  '// Generated by apps/web/scripts/browser-cursor-appearance.mjs; do not edit.\n' +
  `export const browserCursorAppearance = ${JSON.stringify(appearance, null, 2)} as const\n`)
