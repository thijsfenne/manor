// Bakes the fur's pile into src/pile.ts: one square texture of soft light and dark fibres.
// White pixels with alpha are lit fibre crests, black pixels with alpha the shade between
// locks, so the head's colour underneath tints it. Seeded, so every run writes the same file.
//
// It draws on a browser canvas, so it needs Playwright. Point PLAYWRIGHT at its entry when
// it does not resolve from here, for example the copy the verify skill installs.
// usage: node scripts/bake-pile.mjs [px]
import { writeFileSync } from 'node:fs'
import { crc32, deflateSync } from 'node:zlib'
const { chromium } = await import(process.env.PLAYWRIGHT ?? 'playwright')
const out = new URL('../src/pile.ts', import.meta.url)
const px = +(process.argv[2] ?? 192)
const b = await chromium.launch()
const p = await b.newPage()
const data = await p.evaluate((px) => {
  // The tile covers 100 viewBox units, a whole face, so it needs no pattern; it also wraps, so it may be used as one.
  const unit = px / 100
  let seed = 48271
  const rnd = () => (seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0) / 4294967296
  const c = document.createElement('canvas'); c.width = c.height = px
  const g = c.getContext('2d')
  g.fillStyle = 'rgb(128 128 128)'; g.fillRect(0, 0, px, px)
  g.lineCap = 'round'
  const wave = (v, n) => Math.sin((v / px) * Math.PI * 2 * n)
  // Locks: soft, slightly wider smears that give the pile its tufts.
  const stroke = (count, len0, len1, w0, w1, blur, amp) => {
    g.filter = blur ? `blur(${blur * unit}px)` : 'none'
    for (let i = 0; i < count; i++) {
      const x = rnd() * px, y = rnd() * px
      // The coat is combed down and to the right, and wanders. Whole waves per tile, so it wraps.
      const angle = 1.05 + 0.5 * wave(y, 2) + 0.35 * wave(x + y, 1) + (rnd() - 0.5) * 1.5
      const len = (len0 + rnd() * (len1 - len0)) * unit, curl = (rnd() - 0.5) * 0.6 * len
      const dx = Math.cos(angle), dy = Math.sin(angle)
      const v = rnd() < 0.5 ? 255 : 0
      g.strokeStyle = `rgb(${v} ${v} ${v} / ${amp * (0.4 + 0.6 * rnd())})`
      g.lineWidth = (w0 + rnd() * (w1 - w0)) * unit
      for (const ox of [-px, 0, px]) for (const oy of [-px, 0, px]) {
        const m = 8 * unit
        if (x + ox < -m || x + ox > px + m || y + oy < -m || y + oy > px + m) continue
        g.beginPath(); g.moveTo(x + ox, y + oy)
        g.quadraticCurveTo(x + ox + dx * len * 0.5 - dy * curl, y + oy + dy * len * 0.5 + dx * curl, x + ox + dx * len, y + oy + dy * len)
        g.stroke()
      }
    }
  }
  stroke(1300, 1.2, 3, 1.1, 2.2, 0.7, 0.42)   // tufts
  stroke(15000, 0.5, 1.7, 0.4, 0.7, 0.12, 0.5) // fibres
  g.filter = 'none'
  const src = g.getImageData(0, 0, px, px).data
  const dst = g.createImageData(px, px)
  for (let i = 0; i < src.length; i += 4) {
    const v = (src[i] - 128) / 127
    const lit = v > 0
    dst.data[i] = dst.data[i + 1] = dst.data[i + 2] = lit ? 255 : 0
    // Quantised so the PNG packs well; lit fibres carry a little further than the shade.
    dst.data[i + 3] = Math.round(Math.min(1, Math.abs(v) * (lit ? 1.0 : 0.85)) * 255 / 8) * 8
  }
  return Array.from(dst.data)
}, px)
await b.close()
// Grey and alpha only: every pixel is white or black, so two channels carry it and pack far better.
const la = Buffer.alloc(px * (px * 2 + 1))
for (let y = 0; y < px; y++) for (let x = 0; x < px; x++) {
  const i = (y * px + x) * 4, o = y * (px * 2 + 1) + 1 + x * 2
  la[o] = data[i]; la[o + 1] = data[i + 3]
}
const chunk = (type, body) => {
  const len = Buffer.alloc(4); len.writeUInt32BE(body.length)
  const tb = Buffer.concat([Buffer.from(type), body])
  const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(tb))
  return Buffer.concat([len, tb, crc])
}
const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(px, 0); ihdr.writeUInt32BE(px, 4); ihdr[8] = 8; ihdr[9] = 4
const buf = Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(la, { level: 9 })), chunk('IEND', Buffer.alloc(0))])
const uri = 'data:image/png;base64,' + buf.toString('base64')
writeFileSync(out, `// Generated by scripts/bake-pile.mjs. Do not edit; change the script and run it again.\n\n/** The fur's pile, see \`FUR.pile\`: white and black fibres with alpha over one face, ${px}px. */\nexport const PILE =\n  "${uri}";\n`)
console.log(out.pathname, px + 'px', buf.length + ' bytes')
